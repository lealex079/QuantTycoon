"""Export game config to config/LevelConfig.luau.

Reads parameters from the existing sims and writes a strict-typed Luau ModuleScript that
returns one table with no logic. Maker curves are recomputed here with the Level 34 sim:
Level 3 as specified, Level 4 with the informed-bot edge-threshold variant (decided).

Run from anywhere: python3 sim/export_config.py
"""

import math
from pathlib import Path

import numpy as np

import level1_hidden_value as l1
import level2_taker as l2
import level34_maker as mk

OUT = Path(__file__).resolve().parent.parent / "config" / "LevelConfig.luau"

ROUNDS = 100_000
SEED = 12345
# Level 1 error SD constant as written in DESIGN.md (exact value is sqrt(35/12) = 1.7078)
ERROR_SD_PER_SQRT_HIDDEN = 1.708
SCORE_SD_MULTIPLE = 2.0


def num(x: float) -> str:
    return repr(round(float(x), 6))


def num_list(xs: list[float]) -> str:
    return "{ " + ", ".join(num(x) for x in xs) + " }"


def curves() -> list[str]:
    rows: list[str] = []
    for mode in mk.MODES:
        thr_max = mk.THR_MAX if mode == 4 else 0.0
        for dice, hiddens in mk.SETUPS:
            for hidden in hiddens:
                # Same per-config seeding as the sim's threshold runs (SEED + 100*dice + hidden)
                rng = np.random.default_rng(SEED + 100 * dice + hidden)
                r = mk.simulate(rng, mode, dice, hidden, ROUNDS, mk.HALF_SPREADS, thr_max)
                a = int(np.argmax(r["mean"]))
                rows.append(
                    f"\t\t{{ mode = {mode}, dice = {dice}, hidden = {hidden}, "
                    f"bestH = {num(mk.HALF_SPREADS[a])}, bestMean = {num(r['mean'][a])},\n"
                    f"\t\t\tmeans = {num_list(list(r['mean']))} }},"
                )
    return rows


def build() -> str:
    tiers = []
    for tier, dice, hiddens in l1.TIERS:
        tiers.append(f"\t\t{{ tier = {tier}, dice = {dice}, hiddenMin = {min(hiddens)}, hiddenMax = {max(hiddens)} }},")
    grid = [float(h) for h in mk.HALF_SPREADS]
    lines = [
        "--!strict",
        "-- GENERATED by sim/export_config.py. DO NOT EDIT BY HAND; re-run the script instead.",
        f"-- Sims: {ROUNDS:,} rounds, seed {SEED}. Level 4 curves use the informed-bot edge-threshold variant.",
        "",
        "export type Tier = { tier: number, dice: number, hiddenMin: number, hiddenMax: number }",
        "export type Curve = {",
        "\tmode: number, dice: number, hidden: number,",
        "\tbestH: number, bestMean: number,",
        "\tmeans: { number }, -- expected P&L per round at each halfSpreads.grid entry, same order",
        "}",
        "export type LevelConfig = {",
        "\tsides: number,",
        "\ttiers: { Tier },",
        "\tpromotion: { rule: string, goodCalls: number, consecutive: boolean, demote: boolean },",
        "\tlevel1: { errorSdPerSqrtHidden: number, scoreSdMultiple: number },",
        "\tlevel2: { midNoiseMax: number, spread: number },",
        "\tmaker: {",
        "\t\tnoiseTraders: number, toleranceMax: number, informedBots: number,",
        "\t\tinformedSeenDiceRule: string, edgeThresholdMin: number, edgeThresholdMax: number,",
        "\t\thalfSpreads: { min: number, max: number, step: number, grid: { number } },",
        "\t\tcurves: { Curve },",
        "\t},",
        "}",
        "",
        "local config: LevelConfig = {",
        f"\tsides = {l1.SIDES},",
        "\ttiers = {",
        *tiers,
        "\t},",
        '\tpromotion = { rule = "streak", goodCalls = 5, consecutive = true, demote = false },',
        f"\tlevel1 = {{ errorSdPerSqrtHidden = {ERROR_SD_PER_SQRT_HIDDEN}, scoreSdMultiple = {SCORE_SD_MULTIPLE} }},",
        f"\tlevel2 = {{ midNoiseMax = {l2.SHIFT_MAX}, spread = {l2.SPREAD} }}, -- mid = dice * 3.5 + U(-midNoiseMax, +midNoiseMax)",
        "\tmaker = {",
        f"\t\tnoiseTraders = {mk.N_NOISE}, toleranceMax = {mk.TOL_MAX}, informedBots = {mk.N_INFORMED},",
        '\t\tinformedSeenDiceRule = "ceil(dice / 2)",',
        f"\t\tedgeThresholdMin = 0, edgeThresholdMax = {mk.THR_MAX},",
        f"\t\thalfSpreads = {{ min = {num(grid[0])}, max = {num(grid[-1])}, step = 0.25,",
        f"\t\t\tgrid = {num_list(grid)} }},",
        "\t\tcurves = {",
        *curves(),
        "\t\t},",
        "\t},",
        "}",
        "",
        "return config",
        "",
    ]
    return "\n".join(lines)


def main() -> None:
    OUT.parent.mkdir(exist_ok=True)
    OUT.write_text(build())
    print(f"Wrote {OUT} ({OUT.stat().st_size:,} bytes)")


if __name__ == "__main__":
    main()
